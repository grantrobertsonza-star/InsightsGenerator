// Saved crosstabs as PowerPoint slides (the crosstab export's pptx and pdf formats; the pdf is this
// deck converted by LibreOffice). A plain working table, not the branded narrative deck: the point is
// the numbers, laid out as the workspace shows them, in native (editable) PowerPoint tables.
//
// GT-005 (Codex, 2026-10-17): the first layout used fixed widths 0.47 inches wider than the slide,
// so Total was clipped. The first repair (ffa7adc) fitted the width but estimated wrapped height
// from an average character width and never rechecked an oversized row, so wide glyphs and very
// long answer or banner labels still ran off the bottom of the slide and over the footer, and the
// PDF lost answers (Codex review of ffa7adc). The layout now works as follows.
//   - Text is measured with per-character advance widths for the style it is set in (Carlito,
//     metric-compatible with Calibri; tables generated by scripts/crosstab-slides/font-metrics.py),
//     plus a safety margin, and wrapped word by word as the renderer does. Characters outside the
//     tables count as a full em. Cell margins are set explicitly so the estimate uses the real ones.
//   - Width: answer column, banner columns and Total always fit within the slide margins; a banner
//     column never gets narrower than MIN_DATA_COL, and a wider banner is split across slides, each
//     repeating the answer column, Total and the base row.
//   - Height: rows are paged by their estimated wrapped height. A row that would not fit even on a
//     fresh slide is split at its wrap points: the first part fills the room left on the current
//     slide, the rest continues on the next ones, marked "(cont.)". Its figures appear once, on the
//     first part. Joined, the parts are the original label exactly.
//   - Banner headings too tall to sit above the table are replaced by their column letters, and a
//     column key slide before the table gives each letter's full heading.
//   - A continuation slide repeats its question's heading and base row (shortened if long; the full
//     text is where it first appears). Every slide carries the weighting, base and source note (a
//     very long source file name is shortened in the middle, with "...").
//   - A long table name gets a smaller title font and the table starts lower.
// What cannot be laid out truthfully (a table name too long for any title area, a row that cannot
// fit one line) throws CrosstabLayoutError, which the export route returns as a visible refusal
// rather than a clipped slide. The estimate is cautious, not exact. crosstabSlides.test.ts checks
// the planned heights and complete content for every tested shape, and that the PDF LibreOffice
// renders keeps every answer and stays inside the page and above the footer; it is not a proof for
// every font a viewer's PowerPoint might substitute for Calibri.
