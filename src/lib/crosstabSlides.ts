function charEm(cp: number, style: TextStyle): number {
  const [ascii, latin] = WIDTHS[style];
  if (cp >= 32 && cp <= 126) return ascii[cp - 32] / 1000;
  if (cp >= 160 && cp <= 383) return latin[cp - 160] / 1000;
  return 1;
}

export function lineHeight(pt: number): number {
  return (pt / 72) * LINE_FACTOR;
}

/**
 * Where a cell's text wraps: [start, end) offsets into the original string, one per rendered line,
 * breaking after spaces (word wrap) and inside a word only when the word alone is wider than the
 * line. An explicit newline starts a new line (it is in neither line's slice). Greedy, like the
 * renderer, so the first n lines of a text wrap the same as the first n lines of any longer text
 * that starts with it (which is what lets a long label be cut at its wrap points).
 */
export function wrapOffsets(text: string, width: number, pt: number, style: TextStyle = "regular"): [number, number][] {
  const avail = Math.max(0.05, width - CELL_PAD_W);
  const s = String(text);
  const out: [number, number][] = [];
  let paraStart = 0;
  for (;;) {
    const nl = s.indexOf("\n", paraStart);
    const paraEnd = nl === -1 ? s.length : nl;
    if (paraStart === paraEnd) out.push([paraStart, paraEnd]);
    let start = paraStart;
    while (start < paraEnd) {
      let end = start;
      let used = 0;
      let lastBreak = -1;
      while (end < paraEnd) {
        const cp = s.codePointAt(end)!;
        const w = (charEm(cp, style) * pt * WIDTH_SAFETY) / 72;
        if (used + w > avail && s[end] !== " ") break; // a space may hang past the edge, as rendered
        used += w;
        end += cp > 0xffff ? 2 : 1;
        if (s[end - 1] === " ") lastBreak = end;
      }
      if (end < paraEnd) {
        if (lastBreak > start) end = lastBreak; // break after the last space
        else if (end === start) end = start + (s.codePointAt(start)! > 0xffff ? 2 : 1); // one glyph wider than the line
      }
      out.push([start, end]);
      start = end;
    }
    if (nl === -1) break;
    paraStart = nl + 1;
  }
  return out;
}

function linesFor(text: string, width: number, style: TextStyle): number {
  return wrapOffsets(text, width, FONT_PT, style).length;
}

/** Estimated height of a table row whose cells have these texts and widths, all in one style. */
export function rowHeight(texts: string[], widths: number[], style: TextStyle = "regular"): number {
  const lines = Math.max(1, ...texts.map((t, i) => linesFor(t, widths[i] ?? widths[widths.length - 1], style)));
  return CELL_PAD_H + lines * lineHeight(FONT_PT);
}

export class CrosstabLayoutError extends Error {}

export type SlideLine = {
  label: string;
  cells: string[];
  kind: "question" | "test" | "base" | "answer" | "key";
  question: number;
  /** For a label split over several rows: 0 for the first part (which carries the figures). */
  part?: number;
  /** The label as rendered when it differs from `label` ("(cont.) " + a later part). */
  shown?: string;
  /** A heading or base row repeated on a continuation slide (not new content). */
  repeat?: boolean;
};

/** The style a line is set in: question headings bold, test and base rows italic. */
export function styleOf(ln: SlideLine): TextStyle {
  return ln.kind === "question" || ln.kind === "key" ? "bold" : ln.kind === "test" || ln.kind === "base" ? "italic" : "regular";
}

export const shownLabel = (ln: SlideLine) => ln.shown ?? ln.label;
export const lineTexts = (ln: SlideLine) => [shownLabel(ln), ...ln.cells];
export const lineHeightOf = (ln: SlideLine, widths: number[]) => rowHeight(lineTexts(ln), widths, styleOf(ln));

/** Columns per slide, given the banner column count. */
export function columnGroups(columnCount: number): number[][] {
  const perSlide = Math.max(1, Math.floor((TABLE_W - LABEL_COL - TOTAL_COL) / MIN_DATA_COL));
  const groups: number[][] = [];
  for (let start = 0; start < columnCount; start += perSlide) {
    groups.push(Array.from({ length: Math.min(perSlide, columnCount - start) }, (_, i) => start + i));
  }
  return groups.length > 0 ? groups : [[]];
}

/** Column widths for one slide: answer, the group's banner columns, Total. Sum <= TABLE_W. */
export function columnWidths(groupSize: number): number[] {
  const dataW = groupSize > 0 ? (TABLE_W - LABEL_COL - TOTAL_COL) / groupSize : 0;
  return [LABEL_COL, ...Array.from({ length: groupSize }, () => dataW), TOTAL_COL];
}

const CONT = "(cont.) ";

/** Part `part` of a line from label offset `pos` (to the end); later parts drop the figures. */
function partFrom(ln: SlideLine, pos: number, part: number): SlideLine {
  const text = ln.label.slice(pos);
  return { ...ln, label: text, shown: part === 0 ? undefined : CONT + text, cells: part === 0 ? ln.cells : ln.cells.map(() => ""), part };
}

/**
 * The label offset where a part starting at `pos` must end to fit `room` inches, or `pos` when not
 * even one line (or the part's figures) fits.
 */
function partEnd(ln: SlideLine, pos: number, part: number, widths: number[], room: number): number {
  const piece = partFrom(ln, pos, part);
  const style = styleOf(ln);
  const maxLines = Math.floor((room - CELL_PAD_H) / lineHeight(FONT_PT) + 1e-9);
  const cellLines = Math.max(1, ...piece.cells.map((c, i) => linesFor(c, widths[i + 1] ?? widths[widths.length - 1], style)));
  if (maxLines < cellLines) return pos;
  const prefix = part === 0 ? "" : CONT;
  const offsets = wrapOffsets(prefix + piece.label, widths[0], FONT_PT, style);
  if (offsets.length <= maxLines) return ln.label.length;
  return Math.max(pos, pos + offsets[maxLines - 1][1] - prefix.length);
}

/** Splits a line into parts that each fit maxH (used for column key rows). */
export function splitLine(ln: SlideLine, widths: number[], maxH: number): SlideLine[] {
  if (lineHeightOf(ln, widths) <= maxH) return [ln];
  const parts: SlideLine[] = [];
  let pos = 0;
  while (pos < ln.label.length) {
    const end = partEnd(ln, pos, parts.length, widths, maxH);
    if (end <= pos) throw new CrosstabLayoutError("A table row cannot fit on a slide.");
    const p = partFrom(ln, pos, parts.length);
    parts.push({ ...p, label: ln.label.slice(pos, end), shown: p.shown === undefined ? undefined : CONT + ln.label.slice(pos, end) });
    pos = end;
  }
  return parts;
}

/** A repeated label kept to CONTEXT_LINES lines (the full text is where it first appears). */
function shortened(label: string, width: number, suffix: string, style: TextStyle): string {
  const marked = `${label}${suffix}`;
  if (linesFor(marked, width, style) <= CONTEXT_LINES) return marked;
  let keep = label.slice(0, wrapOffsets(label, width, FONT_PT, style)[CONTEXT_LINES - 1][1]).trimEnd();
  while (keep.length > 0 && linesFor(`${keep}...${suffix}`, width, style) > CONTEXT_LINES) keep = keep.slice(0, -1).trimEnd();
  return `${keep}...${suffix}`;
}

export type SlidePlan = {
  kind: "table" | "key";
  columns: number[];
  widths: number[];
  header: string[];
  rows: SlideLine[];
  continued: boolean;
  groupIndex: number;
  groupCount: number;
  /** Where the table starts (below the title). */
  top: number;
};

export type PlanOptions = { top?: number; columnKeys?: string[] };

/** Key-slide geometry: the heading is the label (wide column, rendered second), the key its cell. */
const KEY_WIDTHS = [1.2, TABLE_W - 1.2];
const KEY_LABEL_FIRST = [KEY_WIDTHS[1], KEY_WIDTHS[0]];

/**
 * Plans every slide for one table: banner columns split into groups that fit the width, and each
 * group's rows paged so the estimated table height stays within top..TABLE_BOTTOM. A slide that
 * starts inside a question repeats that question's heading (marked continued) and base row. When a
 * group's banner headings are too tall, a column key slide comes first and the header uses keys.
 */
export function planCrosstabSlides(header: string[], lines: SlideLine[], options: PlanOptions = {}): SlidePlan[] {
  const top = options.top ?? TABLE_TOP;
  const columnCount = header.length - 2; // Answer + banner columns + Total
  const keys = options.columnKeys ?? Array.from({ length: columnCount }, (_, j) => String(j + 1));
  const groups = columnGroups(columnCount);
  const plans: SlidePlan[] = [];
  const budgetAll = TABLE_BOTTOM - top;
  groups.forEach((group, groupIndex) => {
    const widths = columnWidths(group.length);
    const common = { columns: group, groupIndex, groupCount: groups.length, top };
    let groupHeader = [header[0], ...group.map((j) => header[j + 1]), header[header.length - 1]];
    if (rowHeight(groupHeader, widths, "bold") > HEADER_MAX) {
      groupHeader = [header[0], ...group.map((j) => keys[j]), header[header.length - 1]];
      if (rowHeight(groupHeader, widths, "bold") > HEADER_MAX) throw new CrosstabLayoutError("The column headings cannot fit on a slide.");
      // Column key: each key with its full heading, paged like any table.
      const keyHeader = ["Column", "Heading"];
      const keyBudget = budgetAll - rowHeight(keyHeader, KEY_WIDTHS, "bold");
      let page: SlideLine[] = [];
      let used = 0;
      let continued = false;
      const flushKey = () => {
        if (page.length) plans.push({ ...common, kind: "key", widths: KEY_WIDTHS, header: keyHeader, rows: page, continued });
        page = [];
        used = 0;
        continued = true;
      };
      for (const j of group) {
        const keyLine: SlideLine = { label: header[j + 1], cells: [keys[j]], kind: "key", question: -1 };
        for (const ln of splitLine(keyLine, KEY_LABEL_FIRST, keyBudget)) {
          const h = lineHeightOf(ln, KEY_LABEL_FIRST);
          if (page.length && used + h > keyBudget) flushKey();
          page.push(ln);
          used += h;
        }
      }
      flushKey();
    }
    const budget = budgetAll - rowHeight(groupHeader, widths, "bold");
    const pick = (cells: string[]) => [...group.map((j) => cells[j] ?? ""), cells[cells.length - 1] ?? ""];
    const project = (ln: SlideLine): SlideLine => ({ ...ln, cells: pick(ln.cells) });
    const heightOf = (ln: SlideLine) => lineHeightOf(ln, widths);
    const contextFor = (q: number, current: SlideLine): SlideLine[] => {
      if (current.kind === "question") return [];
      const heading = lines.find((x) => x.question === q && x.kind === "question");
      const base = lines.find((x) => x.question === q && x.kind === "base");
      const out: SlideLine[] = [];
      if (heading) out.push(project({ ...heading, label: shortened(heading.label, widths[0], " (continued)", "bold"), repeat: true }));
      if (base && current.kind !== "base") out.push(project({ ...base, label: shortened(base.label, widths[0], "", "italic"), repeat: true }));
      return out;
    };
    let page: SlideLine[] = [];
    let used = 0;
    let continued = false;
    const newSlide = (next: SlideLine) => {
      if (page.length > 0) plans.push({ ...common, kind: "table", widths, header: groupHeader, rows: page, continued });
      page = [];
      used = 0;
      continued = true;
      for (const c of contextFor(next.question, next)) {
        page.push(c);
        used += heightOf(c);
      }
    };
    const place = (ln: SlideLine) => {
      page.push(ln);
      used += heightOf(ln);
    };
    for (const original of lines) {
      const ln = project(original);
      const h = heightOf(ln);
      const contextH = contextFor(ln.question, ln).reduce((s, c) => s + heightOf(c), 0);
      if (used + h <= budget) {
        place(ln);
        continue;
      }
      if (h <= budget - contextH) {
        // Fits on a fresh slide: move it whole rather than split it.
        newSlide(ln);
        place(ln);
        continue;
      }
      // Taller than any slide can hold: fill the room left here, continue on the next slides.
      let pos = 0;
      let part = 0;
      const minRoom = CELL_PAD_H + MIN_PART_LINES * lineHeight(FONT_PT);
      if (budget - used < minRoom && page.some((x) => !x.repeat)) newSlide(ln);
      for (;;) {
        const end = partEnd(ln, pos, part, widths, budget - used);
        if (end <= pos) {
          if (!page.some((x) => !x.repeat)) throw new CrosstabLayoutError("A table row cannot fit on a slide.");
          newSlide(ln);
          continue;
        }
        const p = partFrom(ln, pos, part);
        const text = ln.label.slice(pos, end);
        place({ ...p, label: text, shown: p.shown === undefined ? undefined : CONT + text });
        pos = end;
        part++;
        if (pos >= ln.label.length) break;
        newSlide(ln);
      }
    }
    if (page.length > 0) plans.push({ ...common, kind: "table", widths, header: groupHeader, rows: page, continued });
  });
  return plans;
}

export function crosstabLines(r: CrosstabResult): { header: string[]; lines: SlideLine[]; columnKeys: string[] } {
  const cols = r.columns;
  const header = ["Answer", ...cols.map((c) => (c.letter ? `${c.letter}: ${c.name}` : c.name)), "Total"];
  const columnKeys = cols.map((c, j) => c.letter || String(j + 1));
  const blank = () => header.slice(1).map(() => "");
  const lines: SlideLine[] = [];
  r.questions.forEach((q, qi) => {
    lines.push({ label: q.label, cells: blank(), kind: "question", question: qi });
    const tt = q.tableTests?.[0];
    if (tt) {
      lines.push({
        label: `Whole-table test: ${tt.label} ${tt.p < 0.001 ? "p<0.001" : `p=${tt.p}`} (chi-square ${tt.chi2}, df ${tt.df})`,
        cells: blank(),
        kind: "test",
        question: qi,
      });
    }
    const asPct = q.kind === "single" || q.kind === "multi";
    for (const row of q.rows) {
      if (row.isBase) {
        if (row.isEffBase) continue; // one base row per question is enough on a slide
        lines.push({ label: row.label, cells: [...cols.map((_c, j) => String(row.count[j] ?? "")), String(row.total.count ?? "")], kind: "base", question: qi });
        continue;
      }
      const rowAsPct = asPct && !row.isScore;
      const fmt = (v: number | null | undefined): string => {
        if (v === null || v === undefined) return "-";
        if (!rowAsPct) return row.isMean ? v.toFixed(2) : `${v > 0 ? "+" : ""}${v.toFixed(1)}`;
        return `${v}%`;
      };
      lines.push({ label: row.label, cells: [...cols.map((_c, j) => fmt(row.pct[j])), fmt(row.total.pct)], kind: "answer", question: qi });
    }
  });
  return { header, lines, columnKeys };
}


/** Title font and the height it needs, for the longest suffix any of the table's slides can get. */
export function planTitle(label: string): { pt: number; top: number } {
  const longest = `${label} (column key) (columns 999-999 of 999) (continued)`;
  for (const pt of [18, 14, 12]) {
    const lines = wrapOffsets(longest, TABLE_W + CELL_PAD_W, pt, "bold").length;
    const h = lines * lineHeight(pt) + 0.1;
    if (pt > 12 && lines > 1) continue;
    const top = Math.max(TABLE_TOP, TITLE_Y + h + 0.1);
    if (TABLE_BOTTOM - top < 2.5) throw new CrosstabLayoutError("The table's name is too long to lay out on a slide.");
    return { pt, top };
  }
  throw new CrosstabLayoutError("The table's name is too long to lay out on a slide.");
}
/** The source note, kept to two lines: a long source file name is shortened in the middle, visibly. */
export function footerNote(r: CrosstabResult): string {
  const baseRow = r.questions[0]?.rows.find((x) => x.isBase);
  const make = (source: string | undefined) => [
    r.weightVar ? `Weighted by ${r.weightLabel ?? r.weightVar}` : "Unweighted",
    baseRow ? `base ${baseRow.total.count ?? "?"}` : "",
    source ? `source: ${source}` : "",
  ].filter(Boolean).join(" · ");
  const fits = (s: string) => wrapOffsets(s, TABLE_W + CELL_PAD_W, FOOTER_PT, "regular").length <= 2;
  let source = r.provenance?.sourceFile ?? undefined;
  if (!source || fits(make(source))) return make(source);
  const full = source;
  for (let keep = Math.floor(full.length / 2); keep > 4; keep--) {
    source = `${full.slice(0, keep)}...${full.slice(-keep)}`;
    if (fits(make(source))) return make(source);
  }
  return make(undefined);
}


/** Adds one table's slides to the deck (see the file comment for the layout and its limits). */
export function addCrosstabSlides(pptx: PptxGenJS, label: string, r: CrosstabResult): void {
  const { header, lines, columnKeys } = crosstabLines(r);
  const title = planTitle(label);
  const note = footerNote(r);
  const plans = planCrosstabSlides(header, lines, { top: title.top, columnKeys });
  const columnCount = header.length - 2;
  for (const plan of plans) {
    const slide = pptx.addSlide();
    const columnsNote = plan.groupCount > 1 ? ` (columns ${plan.columns[0] + 1}-${plan.columns[plan.columns.length - 1] + 1} of ${columnCount})` : "";
    const keyNote = plan.kind === "key" ? " (column key)" : "";
    slide.addText(`${label}${keyNote}${columnsNote}${plan.continued ? " (continued)" : ""}`, {
      x: MARGIN_X, y: TITLE_Y, w: TABLE_W, h: plan.top - TITLE_Y - 0.05, fontSize: title.pt, bold: true, color: "1E2761", fontFace: "Calibri", valign: "top", margin: 0,
    });
    const headerRow = plan.header.map((h) => ({ text: h, options: { bold: true, fill: { color: "EEF2FF" }, color: "1E2761" } }));
    const body: PptxGenJS.TableRow[] = plan.rows.map((ln) => {
      if (plan.kind === "key") {
        return [
          { text: ln.cells[0] ?? "", options: { bold: true, align: "left" as const } },
          { text: shownLabel(ln), options: { bold: true, align: "left" as const } },
        ];
      }
      const style = styleOf(ln);
      return [
        { text: shownLabel(ln), options: { bold: style === "bold", italic: style === "italic", align: "left" as const } },
        ...ln.cells.map((c) => ({ text: c, options: { italic: style === "italic", align: "right" as const } })),
      ];
    });
    slide.addTable([headerRow, ...body], {
      x: MARGIN_X,
      y: plan.top,
      w: plan.widths.reduce((a, b) => a + b, 0),
      colW: plan.widths,
      fontSize: FONT_PT,
      fontFace: "Calibri",
      margin: CELL_MARGIN,
      border: { type: "solid", color: "CBD5E1", pt: 0.5 },
      autoPage: false,
    });
    if (note) slide.addText(note, { x: MARGIN_X, y: FOOTER_Y, w: TABLE_W, h: FOOTER_H, fontSize: FOOTER_PT, color: "64748B", fontFace: "Calibri", valign: "top", margin: 0 });
  }
}
